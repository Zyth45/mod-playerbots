#!/usr/bin/env python3
# CoA Economy: writes src/Ai/Coa/Economy/CoaEconomyConfDefaults.inc, the .dist value of every
# AiPlayerbot.CoaEconomy.* and AuctionHouseBot.* key. A key missing from a player's .conf (an install updated
# to 3.0 keeps its old file) then takes the .dist value, not a code default. Run after editing either .dist;
# tests/coa_economy_conf_defaults.cpp fails when the table is stale.
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DISTS = ['conf/playerbots.conf.dist', 'conf/mod_ahbot.conf.dist']
KEY = re.compile(r'^((?:AiPlayerbot\.CoaEconomy|AuctionHouseBot)\.[A-Za-z0-9_.]+)\s*=\s*(.*?)\s*$')


def read_dists(root=ROOT):
    values = {}
    for dist in DISTS:
        with open(os.path.join(root, dist), encoding='utf-8') as f:
            for line in f:
                m = KEY.match(line.rstrip('\n'))
                if m:
                    value = m.group(2)
                    if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
                        value = value[1:-1]
                    values[m.group(1)] = value
    return values


def main():
    values = read_dists()
    out = os.path.join(ROOT, 'src', 'Ai', 'Coa', 'Economy', 'CoaEconomyConfDefaults.inc')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by apps/coa_economy/gen_conf_defaults.py from the two .dist files: do not edit.\n')
        for key in sorted(values):
            # MSVC takes at most 16,380 characters per literal piece: long lists go in adjacent pieces.
            value = values[key]
            pieces = [value[i:i + 8000] for i in range(0, len(value), 8000)] or ['']
            f.write('{"%s", %s},\n' % (key, ' '.join('R"coa(%s)coa"' % p for p in pieces)))
    print(len(values), 'keys ->', out)


if __name__ == '__main__':
    main()
