  `short`  VARCHAR(16)      NOT NULL,
  PRIMARY KEY (`locale`, `full`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='CoA 3.0 LIVE : abréviations de joueur';

